<h1>Задание 1 - вывод всех символов внутри скобок</h1>
<?php 
$str = "Hi (my friend)!";
//Тут я узнаю, сколько всего букв в строке, чтобы цикл знал, когда остановиться
$len = strlen($str);
$start = 0;
$end = 0;
//Запускаю первый цикл, он идет по каждой букве с самого начала до конца.
for ($i = 0; $i < $len; $i++) {
    if ($str[$i] == '(') {
        $start = $i; //Запомнили место первой скобки
    }
    if ($str[$i] == ')') {
        $end = $i;   //Запомнили место второй скобки
    }
}

//Теперь запускаю второй цикл. Он идет не с начала строки, а от первой скобки до второй.
for ($i = $start + 1; $i < $end; $i++) {
    echo $str[$i];
}
?>
<h1>Задание 2 - сколько слов в строке </h1>
<?php 
$str = "I love learning PHP very much.";
$len = strlen($str);
// первое слово в предложении есть всегда
$words = 1;
// Идем по строке от начала до конца
for ($i = 0; $i < $len; $i++) {
    // Если встретили точку, выходим из цикла
    if ($str[$i] == '.') {
        break;
    }
    // Если встретили пробел, началось новое слово,+1
    if ($str[$i] == ' ') {
        $words++;
    }
}
echo "Количество слов: " . $words;
?>
