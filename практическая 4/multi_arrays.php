<h1>Задание 3 - максимальный и минимальный элемент</h1>
<?php
// Двумерный массив 5 строк на 4 столбца (фиксированные данные для примера)
$matrix = [
    [1, 3, 5, 7],
    [44, 23, 8, 12],
    [15, 22, 33, 4],
    [90, 11, 2, 50],
    [9, 6, 88, 10]
];

// Берём самый первый элемент массива как стартовую точку
// Считаем его одновременно и минимальным, и максимальным — это наш «базовый коммит»
$minValue = $matrix[0][0];
$maxValue = $matrix[0][0];

// Храним индексы (координаты) найденных минимума и максимума
// Формат: [номер строки, номер столбца]
// Изначально указываем на первый элемент — пока он и есть экстремум
$minIndex = [0, 0]; // строка 0, столбец 0
$maxIndex = [0, 0]; // строка 0, столбец 0

// Получаем размеры матрицы, чтобы не пересчитывать их в каждом шаге цикла
$rows = count($matrix);          // количество строк (в нашем случае 5)
$cols = count($matrix[0]);       // количество столбцов (в нашем случае 4)

// Внешний цикл: перебираем строки по индексу $i (от 0 до $rows - 1)
for ($i = 0; $i < $rows; $i++) {
    // Внутренний цикл: перебираем столбцы по индексу $j (от 0 до $cols - 1)
    for ($j = 0; $j < $cols; $j++) {
        // $current — это «текущий» элемент, который мы сейчас проверяем
        // Например, на первой итерации это $matrix[0][0], потом $matrix[0][1] и т.д.
        $current = $matrix[$i][$j];

        // Сравниваем $current с текущим минимумом
        // Если текущий элемент меньше того, что мы уже считали минимумом — обновляем
        if ($current < $minValue) {
            $minValue = $current;      // теперь это новый минимум
            $minIndex = [$i, $j];      // запоминаем его координаты: строка $i, столбец $j
        }

        // Аналогично для максимума: если $current больше текущего максимума — обновляем
        if ($current > $maxValue) {
            $maxValue = $current;      // теперь это новый максимум
            $maxIndex = [$i, $j];      // запоминаем его координаты
        }
    }
}

// Вывод результатов в формате, удобном для браузера (HTML)
echo "<h1>Задание 3 — максимальный и минимальный элемент</h1>";
echo "Минимальный элемент: $minValue<br>";
echo "Индексы минимального элемента: строка {$minIndex[0]}, столбец {$minIndex[1]}<br><br>";

echo "Максимальный элемент: $maxValue<br>";
echo "Индексы максимального элемента: строка {$maxIndex[0]}, столбец {$maxIndex[1]}";
?>
